def load_thresholds(overrides=None):
    """Return DEFAULT_THRESHOLDS, optionally overlaid with a config file and/or
    an explicit overrides dict. Config file (quality_config.json or .yaml beside
    this module) is read if present; YAML is read only if PyYAML is installed,
    otherwise it is skipped silently and defaults are used."""
    cfg = dict(DEFAULT_THRESHOLDS)
    here = Path(__file__).resolve().parent
    json_path = here / "quality_config.json"
    yaml_path = here / "quality_config.yaml"
    if json_path.exists():
        cfg.update(json.loads(json_path.read_text()))
    elif yaml_path.exists():
        try:
            import yaml  # optional
            loaded = yaml.safe_load(yaml_path.read_text()) or {}
            cfg.update(loaded)
        except Exception:
            pass  # no PyYAML -> fall back to embedded defaults
    if overrides:
        cfg.update(overrides)
    return cfg


