# ----------------------------------------------------------------------------
# Expected answers for the embedded instructed-response attention checks.
# Each is shown on a different survey branch, so a BLANK cell means "not shown",
# not "failed". (Mirrors scripts/attention_check_report.py in the analysis repo.)
# ----------------------------------------------------------------------------
ATTENTION_CHECKS = {
    "Q220": "Probably okay",        # hypothetical-school-AI branch (no school AI)
    "Q218": "Definitely not okay",  # shown to everyone (comfort-in-school block)
    "Q219": "Probably not okay",    # real-school-AI branch (has school AI)
}

# ----------------------------------------------------------------------------
# TUNE THESE on real data, before looking at outcomes. Record final values in
# QUALITY_CONTROL.md. Defaults are deliberately conservative (favor keeping a
# borderline respondent over dropping a real one).
# ----------------------------------------------------------------------------
DEFAULT_THRESHOLDS = {
    # --- speeding: absolute floors, never SD-based ---
    "total_duration_floor_sec": 180,   # whole multi-block survey faster than this is implausible
    "page_floor_sec": 2.0,             # a single page submitted faster than this = "too fast to read"
    "min_fast_pages_to_flag": 2,       # need >= this many too-fast pages to raise the speeding flag
                                       #   (one stray fast page is noise)
    # --- bot / automation signal ---
    "recaptcha_min": 0.7,              # Qualtrics reCAPTCHA v3 score; below this is suspicious
    "recaptcha_error_is_flag": True,   # Q_RecaptchaStatus == "error" raises its own flag (bot signal)
    # --- attention ---
    "attention_fail_min": 1,           # raise the attention flag at >= this many failed shown checks
    "hard_exclude_if_all_attention_failed": True,  # 0 passed of >=2 shown -> exclude regardless of other flags
    # --- straight-lining (same answer down a whole matrix) ---
    "min_items_for_straightline": 5,   # only judge matrices with >= this many ANSWERED items
                                       #   (uniform answers across a short grid are too plausible)
    "min_straightline_matrices_to_flag": 1,  # raise the flag at >= this many straight-lined matrices
    "straightline_groups": {},         # matrix name -> list of column codes; loaded from config.
                                       #   Attention-check columns are intentionally NOT listed here,
                                       #   so straight-lining and attention stay independent signals.
    # --- open-text content checks (the free-text "walk us through" boxes) ---
    "open_text_cols": ["Q62", "Q63"],  # free-text question short codes screened for content junk
    "duplicate_min_words": 7,          # a cross-respondent duplicate must be at least this substantive
    "duplicate_min_chars": 30,         #   (short collisions like "my own ai account" are NOT duplicates)
    "option_text": [                   # normalized answer-option text; echoes never count as duplicates
        "your own ai account",
        "your schools ai account",
        "an ai that keeps a record of your past work to give faster more personalized help",
        "an ai that keeps no record of your work so nothing about you is stored",
    ],
    "option_echo_jaccard": 0.6,        # token-overlap threshold for "this is basically an option"
    # --- fraud blacklist (read at the quality/analysis stage too) ---
    "fraud_blacklist_path": "",        # "" = auto-discover data/fraud_blacklist.csv near this file/export
    # --- standalone (HARD) exclusion signals: exclude on their own, no >=2 needed ---
    "hard_exclude_signals": [
        "gibberish", "cross_respondent_duplicate", "both_blank_finished",
        "llm_paste_format", "fraud_blacklist",
    ],
    # --- combination rule ---
    "exclude_min_flags": 2,            # exclude when >= this many INDEPENDENT flags trip
    "count_incomplete_toward_exclusion": False,  # incomplete is informational by default
}

# Column-name constants in the Qualtrics export (short-code header row).
COL_DURATION = "Duration (in seconds)"
COL_FINISHED = "Finished"
COL_PROGRESS = "Progress"
COL_RECAPTCHA = "Q_RecaptchaScore"
COL_RECAPTCHA_STATUS = "Q_RecaptchaStatus"
COL_IP = "IPAddress"
COL_RESPONSE_ID = "ResponseId"
ID_PREFERENCE = ("cid", "cid_f", "cid_q", "ResponseId")
PAGE_SUBMIT_SUFFIX = "_Page Submit"


