#!/usr/bin/env python3
"""
quality_filter.py — shared data-quality / exclusion logic for the Teen AI Survey.

CANONICAL SOURCE. Do not edit the vendored copies. Edit this file in the
project root ("AI Survey/quality_filter.py"), then re-run sync_qc.bat to push
identical copies into all consumers:
    - Teen AI Survey Analysis/scripts/quality_filter.py
    - survey_management/response_management/quality_filter.py
    - survey_management/payment_management/quality_filter.py

WHY THIS FILE EXISTS
    Both the analysis repo and the survey-management repo need the *same*
    definition of a low-quality response, and they are separate git repos. To
    keep one rule (not two that drift), the logic lives here, is vendored into
    both, and is regenerated by sync_qc.bat rather than hand-edited in place.

WHAT IT DOES NOT DO
    It does not decide policy. It emits, per respondent, a set of independent
    quality FLAGS plus a recommended exclusion boolean. Each consumer applies
    its own policy:
        - Analysis: drop rows where exclude_recommended is True.
        - Survey management: log quality, and (under IRB clearance) route
          exclude_recommended completers to a Hold bucket for review. Hold means
          "a human decides before paying"; Fraud (the consent blacklist) is the
          only never-pay bucket.

DESIGN
    - Standard library only (csv, json, re, math, statistics, argparse). Runs anywhere,
      no pandas/yaml required. A from_dataframe() helper is provided for repos
      that already hold a pandas frame.
    - Thresholds are ABSOLUTE and pre-set, not SD-based. Response-time
      distributions are right-skewed and the pilot n is tiny (single digits),
      so mean +/- k*SD is unstable and flags the wrong people. Per-page reading
      floors and an absolute total-duration floor are robust at any n.
    - All thresholds live in DEFAULT_THRESHOLDS below and can be overridden by
      passing a dict, or by a quality_config.json / quality_config.yaml beside
      this file. Tune them on real data, BEFORE looking at outcomes, and record
      the final values in QUALITY_CONTROL.md.

CLI
    python quality_filter.py path/to/export.csv [-o quality_report.csv]
    If no path is given, the most recent *.csv in ./ or ../data/ is used.
"""

